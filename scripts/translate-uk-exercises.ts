function buildLookup(obj: Record<string, string>): Map<string, string> {
  const m = new Map<string, string>();
  for (const [k, v] of Object.entries(obj)) m.set(norm(k), v);
  return m;
}

async function main() {
  console.log("Translating exercise prompts/explanations + example sentences…");
  const promptLk = buildLookup(PROMPT_UK);
  const explLk = buildLookup(EXPL_UK);
  const sentLk = buildLookup(SENT_UK);

  const exercises = await db.grammarExercise.findMany();
  let p = 0, e = 0, pMiss = 0;
  const lat = /[A-Za-z]/;
  for (const ex of exercises) {
    const data: Record<string, string | null> = {};
    const pu = promptLk.get(norm(ex.prompt));
    if (pu) { data.promptUk = pu; p++; }
    else if (lat.test(ex.prompt)) pMiss++;
    if (ex.explanation) {
      const eu = explLk.get(norm(ex.explanation));
      if (eu) { data.explanationUk = eu; e++; }
    }
    if (Object.keys(data).length) await db.grammarExercise.update({ where: { id: ex.id }, data });
  }
  console.log(`  ✓ ${p} prompts, ${e} explanations (prompts with English still unmatched: ${pMiss})`);

  const sents = await db.exampleSentence.findMany();
  let s = 0, sMiss = 0;
  for (const x of sents) {
    const su = sentLk.get(norm(x.english));
    if (su) { await db.exampleSentence.update({ where: { id: x.id }, data: { englishUk: su } }); s++; }
    else sMiss++;
  }
  console.log(`  ✓ ${s} example sentences (unmatched: ${sMiss})`);
  console.log("Done.");
}

main()
  .catch((e) => { console.error(e); process.exit(1); })
  .finally(async () => { await db.$disconnect(); });
