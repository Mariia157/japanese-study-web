async function main() {
  console.log("Second-pass Ukrainian translation (prose fields)…");

  // Kanji mnemonics
  let km = 0;
  const kanji = await db.kanji.findMany();
  for (const x of kanji) {
    const uk = KANJI_MNEMONIC_UK[x.character];
    if (uk) { await db.kanji.update({ where: { id: x.id }, data: { mnemonicUk: uk } }); km++; }
  }
  console.log(`  ✓ ${km} kanji mnemonics`);

  // Grammar points: title, explanation, examples
  let gp = 0;
  const points = await db.grammarPoint.findMany();
  for (const p of points) {
    const data: Record<string, string> = {};
    if (GRAMMAR_TITLE_UK[p.slug]) data.titleUk = GRAMMAR_TITLE_UK[p.slug];
    if (GRAMMAR_EXPL_UK[p.slug]) data.explanationUk = GRAMMAR_EXPL_UK[p.slug];
    try {
      const ex = JSON.parse(p.examples) as { jp: string; en: string; note?: string }[];
      const exUk = ex.map((e) => ({ ...e, en: EX_EN_UK[e.en] ?? e.en }));
      data.examplesUk = JSON.stringify(exUk);
    } catch { /* leave examples */ }
    if (Object.keys(data).length) { await db.grammarPoint.update({ where: { id: p.id }, data }); gp++; }
  }
  console.log(`  ✓ ${gp} grammar points`);

  // Grammar section summaries
  let gs = 0;
  const sections = await db.grammarSection.findMany();
  for (const s of sections) {
    const uk = SECTION_SUMMARY_UK[s.slug];
    if (uk) { await db.grammarSection.update({ where: { id: s.id }, data: { summaryUk: uk } }); gs++; }
  }
  console.log(`  ✓ ${gs} grammar section summaries`);

  // Listening / Reading
  async function applyExercise(table: "listeningExercise" | "readingExercise", map: Record<number, ExUk>) {
    let n = 0;
    const rows = await (db[table] as any).findMany();
    for (const r of rows) {
      const u = map[r.id];
      if (!u) continue;
      const data: Record<string, string> = {};
      if (u.title) data.titleUk = u.title;
      if (u.english) data.englishUk = u.english;
      if (u.questions) data.questionsUk = JSON.stringify(u.questions);
      if (Object.keys(data).length) { await (db[table] as any).update({ where: { id: r.id }, data }); n++; }
    }
    return n;
  }
  const l = await applyExercise("listeningExercise", LISTENING_UK);
  console.log(`  ✓ ${l} listening exercises`);
  const rd = await applyExercise("readingExercise", READING_UK);
  console.log(`  ✓ ${rd} reading exercises`);

  console.log("Done.");
}

main()
  .catch((e) => { console.error(e); process.exit(1); })
  .finally(async () => { await db.$disconnect(); });
